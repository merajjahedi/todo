// این فایل برنامه را برای نصب روی دستگاه و استفادهٔ آفلاین به سرویس‌دهندهٔ مرورگر وصل می‌کند.
// اگر مرورگر این امکان را نداشته باشد یا صفحه از فایل باز شده باشد، کاری انجام نمی‌شود.
if ("serviceWorker" in navigator && window.location.protocol !== "file:") {
  // پس از بارگذاری صفحه، فایل مسئول نگهداری نسخهٔ آفلاین را ثبت می‌کند.
  // ورودی رویداد بارگذاری صفحه است؛ خروجی صفحه‌ای ندارد و خطای ثبت را در کنسول نشان می‌دهد.
  window.addEventListener("load", () => {
    // اگر ثبت سرویس‌دهنده ناموفق باشد، خطا برای بررسی نشان داده می‌شود.
    navigator.serviceWorker.register("./service-worker.js").catch((error) => {
      // خطای ثبت را برای بررسی بعدی در ابزارهای برنامه‌نویس مرورگر نشان می‌دهد.
      console.error("Service worker registration failed:", error);
    });
  });
}
